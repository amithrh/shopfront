"""AskOnceCore: everything the AskOnce MCP server needs in ap-southeast-2.

Always created:
  * DynamoDB `askonce` (single table) and `askonce-tasks` (SEP-2663 task store), exactly the key, GSI and
    TTL layout the server's stores expect (docs/design/server-architecture.md section 12,
    server/src/askonce_server/domain/stores/dynamodb.py, packages/mcp-tasks/src/mcp_tasks/dynamodb.py).
    On-demand billing, point-in-time recovery off (cost; the data is demo data and reseedable).
  * Four generated Secrets Manager secrets (request-state key, owner-link key, id key, admin token).
    Values are generated by Secrets Manager at deploy time and never appear in code or the template.
  * ECR repository `askonce-mcp` for the arm64 server image.
  * CloudWatch log group `/askonce/mcp` (7 days).

Created only when the context `image_tag` is set (the image must be in ECR first):
  * ECS cluster `askonce`, an arm64 Fargate task definition (container `Main`, port 8000, the
    Express Mode contract), a least-privilege task role, and the ECS Express Mode service
    (`AWS::ECS::ExpressGatewayService`), which provisions the HTTPS load balancer, certificate, URL and
    auto scaling. CloudFormation has no `CpuArchitecture` on that resource, so the service runs our own
    task definition (which carries the ARM64 runtime platform).

The service URL is only known after the service exists, but the server must be told its public host
(`ASKONCE_ALLOWED_HOSTS` etc.). Context `public_host` supplies it; without it a placeholder
(`pending.invalid`) is used, the container still starts and passes health checks, and /mcp answers 421
until a second deploy passes the real host. infra/deploy.sh runs both phases.
"""

from __future__ import annotations

from aws_cdk import (
    CfnOutput,
    Duration,
    RemovalPolicy,
    Stack,
)
from aws_cdk import aws_dynamodb as dynamodb
from aws_cdk import aws_ecr as ecr
from aws_cdk import aws_ecs as ecs
from aws_cdk import aws_iam as iam
from aws_cdk import aws_logs as logs
from aws_cdk import aws_secretsmanager as secretsmanager
from constructs import Construct

PROJECT_REGION = "ap-southeast-2"
TABLE_NAME = "askonce"
TASKS_TABLE_NAME = "askonce-tasks"
REPOSITORY_NAME = "askonce-mcp"
CLUSTER_NAME = "askonce"
SERVICE_NAME = "askonce-mcp"
LOG_GROUP_NAME = "/askonce/mcp"
CONTAINER_NAME = "Main"  # required by Express Mode for a customer-managed task definition
CONTAINER_PORT = 8000
HEALTH_CHECK_PATH = "/health"
PLACEHOLDER_HOST = "pending.invalid"

# DynamoDB actions the server actually issues (TransactWriteItems is authorised per item as
# PutItem / UpdateItem / DeleteItem). No Scan, no BatchWriteItem, no table management.
MAIN_TABLE_ACTIONS = [
    "dynamodb:GetItem",
    "dynamodb:BatchGetItem",
    "dynamodb:Query",
    "dynamodb:PutItem",
    "dynamodb:UpdateItem",
    "dynamodb:DeleteItem",
]
TASKS_TABLE_ACTIONS = ["dynamodb:GetItem", "dynamodb:PutItem", "dynamodb:Query"]


def normalize_host(value: str) -> str:
    """`https://x.on.aws/` or `x.on.aws` -> `x.on.aws` (the Host header clients send on 443)."""
    host = value.strip()
    for prefix in ("https://", "http://"):
        if host.startswith(prefix):
            host = host[len(prefix) :]
    host = host.split("/", 1)[0]
    if not host or ":" in host or "*" in host:
        raise ValueError(f"public_host must be a bare DNS name (got {value!r})")
    return host.lower()


class AskOnceCoreStack(Stack):
    def __init__(
        self,
        scope: Construct,
        construct_id: str,
        *,
        image_tag: str | None = None,
        public_host: str | None = None,
        min_tasks: int = 1,
        max_tasks: int = 1,
        **kwargs: object,
    ) -> None:
        super().__init__(scope, construct_id, **kwargs)

        # ---- DynamoDB -------------------------------------------------------------------------------
        self.table = dynamodb.Table(
            self,
            "MainTable",
            table_name=TABLE_NAME,
            partition_key=dynamodb.Attribute(name="pk", type=dynamodb.AttributeType.STRING),
            sort_key=dynamodb.Attribute(name="sk", type=dynamodb.AttributeType.STRING),
            billing_mode=dynamodb.BillingMode.PAY_PER_REQUEST,
            time_to_live_attribute="expires_at",
            point_in_time_recovery_specification=dynamodb.PointInTimeRecoverySpecification(
                point_in_time_recovery_enabled=False
            ),
            removal_policy=RemovalPolicy.DESTROY,
        )
        # gsi1: owner inbox by status; gsi2: commitment by task id; gsi3: expiry sweep (sparse).
        # The stores read whole documents from the indexes, so every GSI projects ALL attributes.
        for index in ("gsi1", "gsi2", "gsi3"):
            self.table.add_global_secondary_index(
                index_name=index,
                partition_key=dynamodb.Attribute(name=f"{index}pk", type=dynamodb.AttributeType.STRING),
                sort_key=dynamodb.Attribute(name=f"{index}sk", type=dynamodb.AttributeType.STRING),
                projection_type=dynamodb.ProjectionType.ALL,
            )

        self.tasks_table = dynamodb.Table(
            self,
            "TasksTable",
            table_name=TASKS_TABLE_NAME,
            partition_key=dynamodb.Attribute(name="taskId", type=dynamodb.AttributeType.STRING),
            billing_mode=dynamodb.BillingMode.PAY_PER_REQUEST,
            time_to_live_attribute="expiresAt",
            point_in_time_recovery_specification=dynamodb.PointInTimeRecoverySpecification(
                point_in_time_recovery_enabled=False
            ),
            removal_policy=RemovalPolicy.DESTROY,
        )
        self.tasks_table.add_global_secondary_index(
            index_name="byPrincipal",
            partition_key=dynamodb.Attribute(name="principal", type=dynamodb.AttributeType.STRING),
            sort_key=dynamodb.Attribute(name="createdAt", type=dynamodb.AttributeType.STRING),
            projection_type=dynamodb.ProjectionType.ALL,
        )

        # ---- Secrets (generated by Secrets Manager; never in code or in the template) ----------------
        def generated(construct_id: str, description: str) -> secretsmanager.Secret:
            return secretsmanager.Secret(
                self,
                construct_id,
                description=f"AskOnce {description}",
                generate_secret_string=secretsmanager.SecretStringGenerator(
                    password_length=64,  # alphanumeric: ~380 bits, well over the server's 32-byte minimum
                    exclude_punctuation=True,  # list settings are comma-separated; keep values plain
                    include_space=False,
                ),
                removal_policy=RemovalPolicy.DESTROY,
            )

        self.secrets = {
            "ASKONCE_REQUEST_STATE_KEYS": generated("RequestStateKey", "MRTR request-state key (shared by replicas)"),
            "ASKONCE_OWNER_LINK_KEYS": generated("OwnerLinkKey", "owner-link HMAC key"),
            "ASKONCE_ID_KEY": generated("IdKey", "commitment/task id derivation key"),
            "ASKONCE_ADMIN_TOKEN": generated("AdminToken", "admin token for the owner-link minting route"),
        }

        # ---- ECR and logs ----------------------------------------------------------------------------
        self.repository = ecr.Repository(
            self,
            "Repository",
            repository_name=REPOSITORY_NAME,
            image_scan_on_push=True,
            image_tag_mutability=ecr.TagMutability.IMMUTABLE,
            lifecycle_rules=[ecr.LifecycleRule(description="keep the last 10 images", max_image_count=10)],
            empty_on_delete=True,
            removal_policy=RemovalPolicy.DESTROY,
        )
        self.log_group = logs.LogGroup(
            self,
            "ServiceLogs",
            log_group_name=LOG_GROUP_NAME,
            retention=logs.RetentionDays.ONE_WEEK,
            removal_policy=RemovalPolicy.DESTROY,
        )

        CfnOutput(self, "Region", value=self.region)
        CfnOutput(self, "TableName", value=self.table.table_name)
        CfnOutput(self, "TasksTableName", value=self.tasks_table.table_name)
        CfnOutput(self, "RepositoryUri", value=self.repository.repository_uri)
        CfnOutput(self, "AdminTokenSecretArn", value=self.secrets["ASKONCE_ADMIN_TOKEN"].secret_arn)

        if image_tag:
            self._service(image_tag, normalize_host(public_host) if public_host else None, min_tasks, max_tasks)

    # ---- The Express Mode service -------------------------------------------------------------------
    def _service(self, image_tag: str, public_host: str | None, min_tasks: int, max_tasks: int) -> None:
        host = public_host or PLACEHOLDER_HOST
        origin = f"https://{host}"

        task_role = iam.Role(
            self,
            "TaskRole",
            assumed_by=iam.ServicePrincipal("ecs-tasks.amazonaws.com"),
            description="AskOnce MCP server: DynamoDB on the two AskOnce tables only",
        )
        task_role.add_to_policy(
            iam.PolicyStatement(
                actions=MAIN_TABLE_ACTIONS,
                resources=[self.table.table_arn, f"{self.table.table_arn}/index/*"],
            )
        )
        task_role.add_to_policy(
            iam.PolicyStatement(
                actions=TASKS_TABLE_ACTIONS,
                resources=[self.tasks_table.table_arn, f"{self.tasks_table.table_arn}/index/*"],
            )
        )

        task_definition = ecs.FargateTaskDefinition(
            self,
            "TaskDefinition",
            family=SERVICE_NAME,
            cpu=512,
            memory_limit_mib=1024,
            runtime_platform=ecs.RuntimePlatform(
                cpu_architecture=ecs.CpuArchitecture.ARM64,
                operating_system_family=ecs.OperatingSystemFamily.LINUX,
            ),
            task_role=task_role,
        )
        task_definition.add_container(
            CONTAINER_NAME,
            container_name=CONTAINER_NAME,
            image=ecs.ContainerImage.from_ecr_repository(self.repository, tag=image_tag),
            port_mappings=[
                ecs.PortMapping(container_port=CONTAINER_PORT, name="http", protocol=ecs.Protocol.TCP)
            ],
            logging=ecs.LogDrivers.aws_logs(stream_prefix="mcp", log_group=self.log_group),
            environment={
                "ASKONCE_ENV": "prod",
                "ASKONCE_STORAGE": "dynamodb",
                "ASKONCE_AWS_REGION": self.region,
                "ASKONCE_DYNAMODB_TABLE": self.table.table_name,
                "ASKONCE_DYNAMODB_TASKS_TABLE": self.tasks_table.table_name,
                "ASKONCE_ALLOWED_HOSTS": host,
                "ASKONCE_ALLOWED_ORIGINS": origin,
                "ASKONCE_CORS_ORIGINS": origin,
                "ASKONCE_PUBLIC_BASE_URL": origin,
                "ASKONCE_LOG_LEVEL": "INFO",
                # Tasks only accept traffic from the Express-managed load balancer's security group,
                # so trust its X-Forwarded-* headers (uvicorn proxy_headers).
                "FORWARDED_ALLOW_IPS": "*",
            },
            secrets={name: ecs.Secret.from_secrets_manager(secret) for name, secret in self.secrets.items()},
            stop_timeout=Duration.seconds(30),
        )

        cluster = ecs.CfnCluster(
            self,
            "Cluster",
            cluster_name=CLUSTER_NAME,
            capacity_providers=["FARGATE"],
            default_capacity_provider_strategy=[
                ecs.CfnCluster.CapacityProviderStrategyItemProperty(capacity_provider="FARGATE", weight=1)
            ],
            cluster_settings=[ecs.CfnCluster.ClusterSettingsProperty(name="containerInsights", value="disabled")],
        )

        infrastructure_role = iam.Role(
            self,
            "ExpressInfrastructureRole",
            assumed_by=iam.ServicePrincipal("ecs.amazonaws.com"),
            description="Lets ECS Express Mode manage the load balancer, certificate and scaling for AskOnce",
            managed_policies=[
                iam.ManagedPolicy.from_aws_managed_policy_name(
                    "service-role/AmazonECSInfrastructureRoleforExpressGatewayServices"
                )
            ],
        )

        service = ecs.CfnExpressGatewayService(
            self,
            "Service",
            service_name=SERVICE_NAME,
            cluster=cluster.ref,
            infrastructure_role_arn=infrastructure_role.role_arn,
            task_definition_arn=task_definition.task_definition_arn,
            health_check_path=HEALTH_CHECK_PATH,
            # One task by default: legacy (2025-11-25) MCP sessions live in one process and the
            # Express-managed load balancer has no stickiness. 2026-07-28 traffic is stateless, so
            # raise max_tasks once hosts use the modern protocol only.
            scaling_target=ecs.CfnExpressGatewayService.ExpressGatewayScalingTargetProperty(
                min_task_count=min_tasks,
                max_task_count=max_tasks,
                auto_scaling_metric="AVERAGE_CPU",
                auto_scaling_target_value=70,
            ),
        )
        # The managed policy must be attached before ECS uses the role (it also must outlive the
        # service on delete, so ECS can tear the load balancer down).
        service.node.add_dependency(infrastructure_role)

        CfnOutput(self, "ServiceArn", value=service.attr_service_arn)
        CfnOutput(self, "ServiceEndpoint", value=service.attr_endpoint)
        CfnOutput(self, "ConfiguredPublicHost", value=host)
        CfnOutput(self, "McpUrl", value=f"{origin}/mcp")
